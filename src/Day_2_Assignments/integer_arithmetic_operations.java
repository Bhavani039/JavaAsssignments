package Day_2_Assignments;

public class integer_arithmetic_operations {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a  * b);
        System.out.println(a / b);
        System.out.println(a % b);


    }
}

